import type { StreakMonth } from "@/lib/tauri";

/**
 * Название месяца с годом: «Август 2026».
 *
 * Именительный падеж, поэтому не `Intl`: тот склоняет месяц под дату — «21
 * августа», — а здесь месяц стоит сам по себе, заголовком календаря.
 */
const MONTHS = [
  "Январь",
  "Февраль",
  "Март",
  "Апрель",
  "Май",
  "Июнь",
  "Июль",
  "Август",
  "Сентябрь",
  "Октябрь",
  "Ноябрь",
  "Декабрь",
];

export function monthTitle(month: StreakMonth): string {
  return `${MONTHS[month.month - 1] ?? ""} ${month.year}`.trim();
}
