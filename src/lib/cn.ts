/**
 * Склеивает классы, отбрасывая пустые ветки условий.
 *
 * Полноценный `clsx` тут не нужен: в проекте не бывает ни объектов-словарей
 * классов, ни конфликтов утилит, которые пришлось бы разрешать через
 * `tailwind-merge` — варианты компонентов не пересекаются по свойствам.
 */
export function cn(...parts: (string | false | null | undefined)[]): string {
  return parts.filter(Boolean).join(" ");
}
