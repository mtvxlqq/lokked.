/**
 * Полноэкранный режим окна.
 *
 * Чёрный экран — единственный, кому он нужен, и просить его надо у окна, а не
 * у документа: `requestFullscreen` в webview требует жеста пользователя и
 * рисует поверх страницы свою рамку, а окно Tauri разворачивается по-настоящему
 * и одинаково на всех десктопах. На мобилке метода нет — вызов просто
 * отказывает, и это не повод ломать экран, поэтому ошибки глушатся: не вышло
 * развернуться — студент просто увидит чёрный экран в окне.
 */
export async function setFullscreen(on: boolean): Promise<void> {
  try {
    const { getCurrentWindow } = await import("@tauri-apps/api/window");
    await getCurrentWindow().setFullscreen(on);
  } catch {
    // Окна нет (тесты, браузер) или платформа не умеет — не наша беда.
  }
}
